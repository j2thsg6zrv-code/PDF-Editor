// Without an Apple Developer ID the app ships unsigned, and macOS reports an
// unsigned app downloaded from the internet as "damaged". An ad-hoc signature
// avoids that: macOS then just asks once for permission to open it.
const { execFileSync } = require('child_process');
const path = require('path');

exports.default = async function afterPack(context) {
  if (context.electronPlatformName !== 'darwin') return;
  const appPath = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`);
  execFileSync('codesign', ['--force', '--deep', '--sign', '-', appPath], { stdio: 'inherit' });
};
